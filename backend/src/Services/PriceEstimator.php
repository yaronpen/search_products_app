    private const PREMIUM_WORDS = ['pro', 'פרו', 'מקצועי', 'פרימיום', 'premium', 'ultra', 'max', 'מתקפל', 'oled', 'qled', '4k', 'חכם'];
    private const BUDGET_WORDS = ['בסיסי', 'בסיסיות', 'תקציבי', 'זולות', 'זול', 'מיני', 'mini', 'קומפקטי', 'קטן', 'לילדים'];

    public static function estimate(string $id, string $name, string $subcategory): float
    {
        [$min, $max] = self::RANGES[$subcategory] ?? self::DEFAULT_RANGE;
        $tokens = TextNormalizer::tokenize($name);

        // Position within the range: 0..1, stable per product id
        $position = (crc32($id) % 1000) / 1000;
        if (array_intersect($tokens, self::PREMIUM_WORDS)) {
            $position = 0.6 + $position * 0.4;
        } elseif (array_intersect($tokens, self::BUDGET_WORDS)) {
            $position = $position * 0.35;
        } else {
            $position = 0.1 + $position * 0.6;
        }

        // Log scale so wide ranges (990..24990) aren't dominated by expensive items
        $price = exp(log($min) + (log($max) - log($min)) * $position);
        return self::retailRound($price);
    }

    /** 87 -> 89, 436 -> 439, 1873 -> 1890, 12431 -> 12490 */
    private static function retailRound(float $price): float
    {
        $step = $price < 100 ? 10 : ($price < 1000 ? 10 : 100);
        return (float) (ceil($price / $step) * $step - ($price < 1000 ? 1 : 10));
    }
